// descriptionCache aliases gameDescriptions (kept for internal call sites).
var descriptionCache = gameDescriptions

// Descriptions returns Name->Description for every registered game. The
// returned map is the package's cached copy — callers must not mutate it.
func Descriptions() map[string]string {
	return descriptionCache
}

// Description returns the description for a single game by name, or "" if
// name is unknown.
func Description(name string) string {
	return descriptionCache[name]
}
